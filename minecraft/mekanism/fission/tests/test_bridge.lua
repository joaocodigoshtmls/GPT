local H=dofile('minecraft/mekanism/fission/tests/runtime_harness.lua')
local total=0
local function test(name,fn)
  local ok,err=pcall(fn) assert(ok,name..': '..tostring(err))
  total=total+1 print('OK '..name)
end
local function boot(options)
  local h=H.new(options) h:boot() h:advance(2) return h
end
test('startup SCRAM precedes modules; raw batched snapshot stays complete',function()
  local h=boot()
  assert(not h.active and h.stops>=1)
  local p=h:last('fission_data_v3')
  assert(p.safety.blocked and p.data and p.data.temp==373.15 and p.data.fuelPct==100)
  assert(p.safety.readSeconds<1 and h:read('/fission_binding_v3.json').reactor=='left')
end)
test('missing module still SCRAMs and transmits an error',function()
  local h=H.new() h.missingModule='test_logic' h:boot() h:advance(2)
  assert(not h.active and h.stops>=1)
  assert(h:last('fission_data_v3').safety.reason:find('ERRO INTERNO'))
  local seq=h:last('fission_data_v3').sequence h:advance(3)
  assert(h:last('fission_data_v3').sequence>seq)
end)
test('manual release keeps timers and telemetry alive with real yields',function()
  local h=boot() h:release()
  assert(not h:last('fission_data_v3').safety.blocked)
  local seq=h:last().sequence h:advance(8)
  assert(h:last().sequence>seq+5 and not h.active)
end)
test('test arm and burn controls never activate automatically',function()
  local h=boot() h:release() h:command('startTest') h:advance(1)
  assert(not h.active and h.activations==0)
  h:command('setBurnRate',1) h:advance(1)
  assert(h.rate==1 and not h.active and h:last('fission_ack_v3').ok)
end)
test('manual ONLINE requires clear fault and fresh admission margins',function()
  local h=boot() h:command('setStatus',true) h:advance(.5)
  assert(not h.active and not h:last('fission_ack_v3').ok)
  h:release() h:command('setStatus',true) h:advance(1)
  assert(h.active and h.activations==1 and h:last('fission_ack_v3').ok)
end)
test('wrong sender target session legacy namespace and replay are rejected',function()
  local h=boot() h:release()
  for _,change in ipairs({{source=9},{target=9},{session='wrong'},{type='command'},{utc=0},{utc=math.huge}}) do
    h:command('setStatus',true,change) h:advance(.5) assert(not h.active)
  end
  h:command('setBurnRate',1) h:advance(1) local old=h.commandID
  h:command('setBurnRate',2,{id=old}) h:advance(1)
  assert(h.rate==1)
end)
test('damage trips locally with no panel and stays latched',function()
  local h=boot() h:release() h.active=true h:advance(1)
  h.damage=1 h:advance(1)
  assert(not h.active and h:last('fission_data_v3').safety.blocked)
  assert(h:read('/fission_lock_v3.json'))
  h.damage=0 h:advance(3) assert(not h.active)
end)
test('watchdog protects while sensor tasks are stalled',function()
  local h=boot() h:release() h.active=true h:advance(1)
  h.delays={getTemperature=10}
  h:advance(5)
  assert(not h.active and h:last('fission_data_v3').safety.blocked)
  assert(h:last('fission_data_v3').safety.reason:find('INTERVALO'))
end)
test('activation precondition cannot resume after a watchdog fault and activate',function()
  local h=boot() h:release() h.delays={getStatus=5}
  h:command('setStatus',true) h:advance(12)
  assert(h.activations==0 and not h.active)
end)
test('invalid sensor reading removes stale values and SCRAMs',function()
  local h=boot() h:release() h.active=true h.fuel=0/0 h:advance(2)
  local p=h:last('fission_data_v3')
  assert(not h.active and p.safety.blocked and p.data==nil)
end)
test('storage failure prevents release',function()
  local h=boot() h.diskFail=true h:release()
  assert(h:last('fission_data_v3').safety.blocked and not h.active)
end)
test('CTRL+T enforces SCRAM rather than abandoning control',function()
  local h=boot() h:release() h.active=true h:event('terminate') h:advance(2)
  assert(not h.active and coroutine.status(h.co)~='dead')
  assert(h:last('fission_data_v3').safety.blocked)
end)
test('ONLINE rechecks all safety sensors before activation, not just cached status',function()
  local h=boot() h:release() h.tempC=650
  h:command('setStatus',true) h:advance(2)
  assert(h.activations==0 and not h.active)
  assert(h:last('fission_data_v3').safety.blocked)
end)
test('realistic huge fuel buffer cannot pass without replenishment',function()
  local h=boot() h:release() h:command('startTest') h:advance(1)
  h.active=true
  for _=1,100 do
    h.fuel=h.fuel-10/h.capacity h:advance(1)
    if not h.active then break end
  end
  assert(not h.active and h:last('fission_data_v3').test.state=='FAILED')
  assert(h.files['/fission_results_v3.jsonl'])
end)
test('disconnect never confirms off or silently changes adapter',function()
  local h=boot() h:release() h.active=true h:advance(1)
  h.present=false h:event('peripheral_detach','left') h:advance(2)
  assert(not h:last('fission_data_v3').safety.scramConfirmed)
  h.present=true h:advance(2)
  assert(not h.active and h:last('fission_data_v3').safety.scramConfirmed)
end)
test('corrupt lock and pending marker are preserved and cannot be reboot-cleared',function()
  local h=boot({files={['/fission_lock_v3.json']='corrupt',
    ['/fission_lock_v3.json.pending']='original interrupted transaction'}})
  h:release()
  assert(h:last('fission_data_v3').safety.blocked)
  assert(h.files['/fission_lock_v3.json']=='corrupt')
  assert(h.files['/fission_lock_v3.json.pending']=='original interrupted transaction')
  h:boot() h:advance(2) h:release()
  assert(h:last('fission_data_v3').safety.blocked)
end)
test('emergency events survive a listener suspended inside a command',function()
  for _,event in ipairs({{'terminate'},{'key',31},{'peripheral_detach','left'}}) do
    local h=boot() h:release() h.active=true h:advance(1)
    h:command('setBurnRate',1)
    h:event(table.unpack(event)) h.actual=1 h:advance(2)
    assert(not h.active and h:last('fission_data_v3').safety.blocked,event[1])
  end
end)
test('a complete real-controller trial records pass and keeps protection active',function()
  local h=boot({config={TREND_WINDOW=6,SHORT_WINDOW=2,STABLE_SECONDS=4,
    MEASURE_SECONDS=6,TEST_TIMEOUT=60,PREDICT_SECONDS=2}})
  h:release() h:command('startTest') h:advance(1) h.active=true h:advance(22)
  assert(h:last('fission_data_v3').test.state=='PASSED')
  assert(h.files['/fission_results_v3.jsonl'])
  h.damage=1 h:advance(2)
  assert(not h.active and h:last('fission_data_v3').test.state=='FAILED')
end)
test('failed result persistence cannot report a successful safe test',function()
  local h=boot({config={TREND_WINDOW=6,SHORT_WINDOW=2,STABLE_SECONDS=4,
    MEASURE_SECONDS=6,TEST_TIMEOUT=60,PREDICT_SECONDS=2}})
  h:release() h:command('startTest') h:advance(1) h.active=true
  local done=false
  for _=1,100 do
    h:advance(.25)
    local t=h:last('fission_data_v3').test
    if t.state=='MEASURING' then h.diskFail=true done=true break end
  end
  assert(done) h:advance(12)
  assert(not h.active and h:last('fission_data_v3').safety.blocked)
  assert(h:last('fission_data_v3').safety.reason:find('FALHA AO SALVAR TESTE'))
end)
print(total..' bridge scenarios passed')
